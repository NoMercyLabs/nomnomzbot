/**
 * S-ADMIN gap fix (owner punch list §6, 2026-09-08): revoking an invite code used to fire straight off the
 * trash-icon click, with no confirmation — the only destructive admin action in the dashboard that skipped
 * the project's confirm-dialog pattern. Proves the click no longer revokes anything by itself, the dialog
 * names the exact code about to stop working, and the revoke only actually happens once that is confirmed.
 */
@OptIn(ExperimentalTestApi::class)
class AdminInviteRevokeRenderTest {

    @Composable
    private fun EnglishContent(content: @Composable () -> Unit) {
        AppEnvironment(tag = "en") {
            NomNomzTheme { content() }
        }
    }

    @Composable
    private fun ObservingBillingTab(controller: AdminController) {
        val state by controller.state.collectAsState()
        BillingTab(state = state, controller = controller)
    }

    @Test
    fun revoking_an_invite_code_requires_confirmation_before_it_actually_revokes() {
        val invite = InviteCode(
            id = "invite-1",
            code = "WELCOME-ABC123",
            maxRedemptions = 5,
            redemptionCount = 1,
            grantsFoundersBadge = false,
        )
        val api = FakeAdminApiForInviteRevokeTest(inviteCodes = listOf(invite))
        val controller = AdminController(
            api = api,
            iamApi = FakeIamApiForInviteRevokeTest(),
            platformAdminApi = FakePlatformAdminApiForInviteRevokeTest(),
        )

        runTest { controller.load() }

        runComposeUiTest {
            setContent {
                EnglishContent {
                    ObservingBillingTab(controller = controller)
                }
            }
            waitForIdle()

            // Clicking the row's trash-icon action (an icon-only GlyphButton — its label is a tooltip and
            // contentDescription, not visible text) opens the confirmation — nothing is revoked yet.
            onNodeWithContentDescription("Revoke").performClick()
            waitForIdle()
            assertEquals(0, api.revokeCallCount)

            // The dialog names the exact code that is about to stop working, before the destructive commit
            // (the row behind the dialog still shows its own "WELCOME-ABC123" too, so the assertion targets
            // the dialog's distinct sentence rather than the bare code, which now matches twice).
            onNodeWithText("The code WELCOME-ABC123 stops working immediately", substring = true).assertExists()

            // Confirm the destructive commit — the dialog's own labelled button, distinct from the row's
            // icon-only trigger above (that one carries no visible "Revoke" text at all).
            onNodeWithText("Revoke").performClick()
            waitForIdle()

            assertEquals(1, api.revokeCallCount)
            assertEquals("invite-1", api.lastRevokedInviteCodeId)
        }
    }
}

