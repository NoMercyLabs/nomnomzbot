// Runs after openapi-typescript in `npm run gen:api`: puts the auto-generated marker
// first and the license header beneath it, as CLAUDE.md requires for generated files.
import { readFileSync, writeFileSync } from 'node:fs'

const path = 'src/api/schema.d.ts'
const header = [
  '// <auto-generated />',
  '// -----------------------------------------------------------------------------',
  '//  Copyright (c) NoMercy Labs.',
  '//',
  '//  This file is part of NomNomzBot. You may use, change and share it for free,',
  '//  for any noncommercial purpose, under the PolyForm Noncommercial License',
  '//  1.0.0. You may not earn money with it. Distributed WITHOUT ANY WARRANTY.',
  '//  See LICENSE for details, and TRADEMARKS.md for the name and logo.',
  '//',
  '//  SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0',
  '// -----------------------------------------------------------------------------',
  '',
  '',
].join('\n')

const body = readFileSync(path, 'utf8')
if (!body.startsWith('// <auto-generated />')) {
  writeFileSync(path, header + body)
}
