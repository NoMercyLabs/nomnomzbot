using System.Threading.RateLimiting;

namespace NomNomzBot.Api.RateLimiting;

/// <summary>
/// The live playlist proxy. A player watching a live stream reloads its playlist about every 2 seconds, so one
/// watcher sends about 30 requests a minute. 120 a minute per IP fits four watchers behind one address (the
/// streamer's own devices, or mods on one network); a script that loops the proxy is stopped there.
/// </summary>
public static class LivePlaylistRateLimitPolicy
{
    public const string PolicyName = "live-playlist";
    public const int PermitLimit = 120;
    public static readonly TimeSpan Window = TimeSpan.FromMinutes(1);

    public static RateLimitPartition<string> Partition(HttpContext context) =>
        RateLimitPartition.GetSlidingWindowLimiter(
            $"{PolicyName}:{RateLimitPartitionKeys.Ip(context)}",
            _ =>
                new()
                {
                    PermitLimit = PermitLimit,
                    Window = Window,
                    SegmentsPerWindow = 6,
                    QueueLimit = 0,
                }
        );
}
